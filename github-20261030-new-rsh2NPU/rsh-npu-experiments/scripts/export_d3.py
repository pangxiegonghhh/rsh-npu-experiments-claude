"""Seal all completed D3 evidence and exact binaries/objects, no device work."""
from pathlib import Path
import base64,hashlib,json,zlib
ROOT=Path(__file__).resolve().parents[1];D=ROOT/'results/d3'
def main():
    state=json.loads((D/'progress.json').read_text());assert state['state']=='complete';files={}
    def add(p,name=None):
        b=p.read_bytes();e={'sha256':hashlib.sha256(b).hexdigest()}
        if len(b)>65536:e['base64_zlib']=base64.b64encode(zlib.compress(b)).decode()
        else:
            try:e['text']=b.decode()
            except UnicodeDecodeError:e['base64_zlib']=base64.b64encode(zlib.compress(b)).decode()
        files[name or str(p.relative_to(ROOT))]=e
    for p in sorted(D.rglob('*')):
        if p.is_file() and p.suffix!='.tmp' and not ('plans' in p.relative_to(D).parts and p.suffix=='.bin'):add(p)
    # D3 layouts reuse exact D1 arrays, no numerical input is regenerated by this stage.
    mf=json.loads((D/'case_manifest.json').read_text())
    for name in mf['files']:
        if not name.endswith('.bin'):add(ROOT/name)
    for name in ['prepare_d3','run_d3','analyze_d3','audit_d3','report_d3','export_d3','d3_sequence','restore_d3_runtime','checkpoint_d3']:
        path=ROOT/'scripts'/(name+'.py')
        if path.exists():add(path,'results/d3/source_snapshot/scripts/'+path.name)
    b=json.dumps({'schema':'d3-recovery-v1','files':files,'state':'complete'},ensure_ascii=False).encode();(ROOT.parent/'d3-transfer.txt').write_bytes(b);c={'sha256':hashlib.sha256(b).hexdigest(),'bytes':len(b),'files':len(files),'state':'complete'};(ROOT.parent/'d3-check.txt').write_text(json.dumps(c));print(json.dumps(c),flush=True)
if __name__=='__main__':main()
